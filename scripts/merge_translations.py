import sys
import re
import json
from translations_data import CARD_TRANSLATIONS, LANGS

# Read current src/dataTranslations.ts
with open("src/dataTranslations.ts", "r", encoding="utf-8") as f:
    orig_code = f.read()

# We want to ensure STATIC_TRANSLATIONS has entries for all 11 languages:
# ko, en, ja, zh, th, fr, es, pt, ka, ru, uk

# Let's parse existing STATIC_TRANSLATIONS using a node runner to get exact JSON
import subprocess

cmd = """npx tsx -e '
import { STATIC_TRANSLATIONS } from "./src/dataTranslations";
console.log(JSON.stringify(STATIC_TRANSLATIONS));
'"""
res = subprocess.run(cmd, shell=True, capture_output=True, text=True)
if res.returncode != 0:
    print("Error parsing existing translations:", res.stderr)
    sys.exit(1)

existing_dict = json.loads(res.stdout)
print("Existing languages in STATIC_TRANSLATIONS:", list(existing_dict.keys()))

# Merge CARD_TRANSLATIONS into all languages
for lang in LANGS:
    if lang not in existing_dict:
        existing_dict[lang] = {}

for key, trans_map in CARD_TRANSLATIONS.items():
    for lang, val in trans_map.items():
        if lang in existing_dict:
            existing_dict[lang][key] = val

# Also, if a language like fr, es, pt, ru, uk, ka is missing some festival names, let's copy from English or French
for lang in ["fr", "es", "pt", "ka", "ru", "uk"]:
    for k, v in existing_dict.get("ko", {}).items():
        if k not in existing_dict[lang]:
            # If not yet defined, use English key or CARD_TRANSLATIONS
            pass

# Let's count keys per language now
for lang in LANGS:
    print(f"Language '{lang}' has {len(existing_dict.get(lang, {}))} entries")

# Format into clean TypeScript
output_lines = [
    "// Comprehensive Multi-Language Data Translations for Corea Labs",
    "// Autogenerated and synchronized across all 11 supported languages",
    "export const STATIC_TRANSLATIONS: Record<string, Record<string, string>> = " + json.dumps(existing_dict, ensure_ascii=False, indent=2) + ";",
    ""
]

with open("src/dataTranslations.ts", "w", encoding="utf-8") as f:
    f.write("\n".join(output_lines))

print("Successfully written updated src/dataTranslations.ts!")
